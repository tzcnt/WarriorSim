// Regenerate the integration listing from the captured Warrior source data.
// Usage: node scripts/extract-forever-talents.js
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'data/forever/warrior-source.json'), 'utf8'));
// Live patch notes newer than the client snapshot. The raw snapshot stays unchanged.
const PATCH_DATE = '2026-09-24';
const patches = {
    'Arms:Bloodthrill': {desc: [4, 8, 12, 16, 20].map(chance =>
        `Your main hand melee attacks, including Heroic Strike and Cleave, against targets afflicted by your Rend have a ${chance}% chance to activate your Overpower ability for 1 attack on your current target. Lasts 6 sec.`)},
    'Arms:Improved Slam': {desc: [['1.5', '0.25'], ['3', '0.50']].map(([cooldown, cast]) =>
        `Reduces the cooldown of your Slam ability by ${cooldown} sec, and its global cooldown and cast time by ${cast} sec. In addition, Slam no longer interrupts your melee swing time.`)},
    'Protection:Focused Rage': {row: 5, col: 4},
    'Protection:Bastion': {row: 6, col: 3},
};
const applied = new Set();
const talents = snapshot.warrior.trees.map(tree => {
    const positions = new Set();
    return { n: tree.name, t: tree.talents.map(talent => {
        const patchKey = `${tree.name}:${talent.name}`;
        const patch = patches[patchKey];
        if (patch) applied.add(patchKey);
        const row = patch?.row ?? talent.row, col = patch?.col ?? talent.col;
        const position = `${row}:${col}`;
        assert(!positions.has(position), `Duplicate position: ${tree.name} ${position}`);
        positions.add(position);
        assert(row >= 1 && row <= 7 && col >= 1 && col <= 4);
        assert(Number.isInteger(talent.max) && talent.max > 0);
        assert(!patch?.desc || patch.desc.length === talent.max, `Patched rank count: ${patchKey}`);
        const d = patch?.desc || Array.from({ length: talent.max }, (_, rank) => talent.desc[rank + 1]);
        assert(d.every(text => typeof text === 'string' && text.length));
        const result = {
            i: talent.id,
            n: talent.name,
            m: talent.max,
            s: Array(talent.max).fill(null),
            d,
            x: col - 1,
            y: row - 1,
            iconname: talent.icon,
            c: 0,
        };
        if (talent.req) {
            const parent = tree.talents.findIndex(t => t.name === talent.req);
            assert(parent >= 0, `Missing prerequisite: ${talent.req}`);
            result.r = [parent, tree.talents[parent].max];
        }
        result.forever = {
            key: `${tree.name.toLowerCase()}:${talent.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`,
            passive: talent.passive,
            sourceComplete: true,
            estimatedDescriptionRanks: [],
            tooltip: talent.tooltip,
            implementationStatus: 'unimplemented',
        };
        for (const field of ['cost', 'reqText', 'scaleIdx', 'fixed', 'classic']) {
            if (Object.hasOwn(talent, field)) result.forever[field] = talent[field];
        }
        if (patch) result.forever.patch = PATCH_DATE;
        return result;
    }) };
});
assert.deepEqual([...applied].sort(), Object.keys(patches).sort(), 'Every patch must match a source talent');
assert.deepEqual(talents.map(tree => [tree.n, tree.t.length]), [['Arms', 17], ['Fury', 18], ['Protection', 18]]);
const all = talents.flatMap(tree => tree.t);
assert.equal(new Set(all.map(t => t.forever.key)).size, all.length);
const header = '// Generated by scripts/extract-forever-talents.js; see data/forever/README.md.\n' +
    '// Client tooltips from Hyjal; rank spell IDs are unknown. Runtime handlers are in js/talent-rules.js.\n';
fs.writeFileSync(path.join(root, 'js/data/talents_forever.js'), header +
    'var talentsForever = ' + JSON.stringify(talents, null, 3) + ';\n');
console.log(`Extracted ${all.length} talents with ${all.reduce((n, t) => n + t.d.length, 0)} explicit rank descriptions; ${applied.size} patched from ${PATCH_DATE} notes.`);
